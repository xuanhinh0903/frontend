// Generates Cursor agent config from the Claude Code source of truth.
//
//   CLAUDE.md                     -> .cursor/rules/project.mdc   (alwaysApply: true)
//   .claude/rules/<name>.md       -> .cursor/rules/<name>.mdc    (paths -> globs)
//   .claude/skills/<name>/**      -> .cursor/skills/<name>/**    (copied as is)
//
// Skills must not contain AGENTS.md: Cursor always-applies that filename and it
// would override repo conventions. Keep compiled guides as REFERENCE.md instead.
//
// Parity: both tools must get the same skills and behave the same with them, so a
// SKILL.md may only use portable frontmatter keys and must not name tools that
// exist in one agent only. Fix a third-party skill locally or do not use it.
//
// Usage: node scripts/sync-agents.mjs --write | --check
// --check exits with code 1 and lists every drifted file.

import fs from 'node:fs'
import path from 'node:path'
import process from 'node:process'

const ROOT = process.cwd()
const SOURCE_ENTRY = 'CLAUDE.md'
const SOURCE_RULES = '.claude/rules'
const SOURCE_SKILLS = '.claude/skills'
const TARGET_RULES = '.cursor/rules'
const TARGET_SKILLS = '.cursor/skills'
const MARKER = 'Generated by scripts/sync-agents.mjs'

// Frontmatter keys every agent reads the same way. Anything else (allowed-tools,
// hidden, user-invocable, argument-hint, model, hooks...) changes behaviour in
// one tool only.
const PORTABLE_SKILL_KEYS = new Set([
  'name',
  'description',
  'license',
  'metadata',
  'version',
  'compatibility',
])
// Tool names that exist in Claude Code only; a skill that calls them behaves
// differently in Cursor.
const TOOL_ONLY_NAMES = /\b(WebFetch|WebSearch|AskUserQuestion|TodoWrite)\b/

/** @param {string} rel */
function abs(rel) {
  return path.join(ROOT, rel)
}

/** @param {string} rel */
function toPosix(rel) {
  return rel.split(path.sep).join('/')
}

/** @param {string} dirRel */
function listFiles(dirRel) {
  const dir = abs(dirRel)
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir, { recursive: true })
    .map((entry) => path.join(dirRel, String(entry)))
    .filter((rel) => fs.statSync(abs(rel)).isFile())
    .map(toPosix)
    .sort()
}

/** @param {string} dirRel */
function listDirs(dirRel) {
  const dir = abs(dirRel)
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir)
    .filter((name) => fs.statSync(path.join(dir, name)).isDirectory())
    .sort()
}

/** @param {string} value */
function unquote(value) {
  return value.trim().replace(/^["']|["']$/g, '')
}

/** @typedef {Record<string, string | string[]>} Frontmatter */

// Minimal frontmatter parser: scalar values and string lists (block or inline).
/**
 * @param {string} text
 * @returns {{ data: Frontmatter, body: string }}
 */
function parseFrontmatter(text) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text)
  if (!match) return { data: {}, body: text }
  /** @type {Frontmatter} */
  const data = {}
  /** @type {string[] | null} */
  let list = null
  for (const line of (match[1] ?? '').split(/\r?\n/)) {
    const item = /^\s*-\s+(.*)$/.exec(line)
    if (item && list) {
      list.push(unquote(item[1] ?? ''))
      continue
    }
    const pair = /^([\w-]+):\s*(.*)$/.exec(line)
    if (!pair) continue
    const [, key = '', raw = ''] = pair
    list = null
    if (raw === '') {
      list = []
      data[key] = list
    } else if (raw.startsWith('[')) {
      data[key] = raw
        .replace(/^\[|\]$/g, '')
        .split(',')
        .map(unquote)
        .filter(Boolean)
    } else {
      data[key] = unquote(raw)
    }
  }
  return { data, body: text.slice(match[0].length) }
}

/**
 * @param {{ description: string, globs?: string, alwaysApply: boolean }} meta
 * @param {string} source
 * @param {string} body
 */
function renderMdc({ description, globs, alwaysApply }, source, body) {
  const lines = ['---', `description: ${description}`]
  if (globs) lines.push(`globs: ${globs}`)
  lines.push(`alwaysApply: ${alwaysApply}`, '---', '')
  lines.push(
    `<!-- ${MARKER} from ${source}. Edit the source, then run yarn agents:sync. -->`,
    '',
  )
  return lines.join('\n') + body.replace(/^\s+/, '')
}

/** @typedef {Map<string, Buffer>} Expected */

// Map of target path -> expected file content (Buffer).
/** @returns {Expected} */
function buildExpected() {
  /** @type {Expected} */
  const expected = new Map()

  const entry = fs.readFileSync(abs(SOURCE_ENTRY), 'utf8')
  expected.set(
    `${TARGET_RULES}/project.mdc`,
    Buffer.from(
      renderMdc(
        {
          description: 'Project instructions for every task',
          alwaysApply: true,
        },
        SOURCE_ENTRY,
        entry,
      ),
    ),
  )

  for (const rel of listFiles(SOURCE_RULES).filter((f) => f.endsWith('.md'))) {
    const { data, body } = parseFrontmatter(fs.readFileSync(abs(rel), 'utf8'))
    const paths = Array.isArray(data.paths) ? data.paths : []
    const name = path.posix.relative(SOURCE_RULES, rel).replace(/\.md$/, '.mdc')
    if (name === 'project.mdc') {
      throw new Error(`${rel} collides with the generated project.mdc`)
    }
    const description =
      typeof data.description === 'string' ? data.description : ''
    const meta = {
      description: description || name.replace(/\.mdc$/, ''),
      globs: paths.join(','),
      alwaysApply: paths.length === 0,
    }
    expected.set(
      `${TARGET_RULES}/${name}`,
      Buffer.from(renderMdc(meta, rel, body)),
    )
  }

  for (const skill of listDirs(SOURCE_SKILLS)) {
    for (const rel of listFiles(`${SOURCE_SKILLS}/${skill}`)) {
      if (path.posix.basename(rel) === 'AGENTS.md') continue
      const target = `${TARGET_SKILLS}/${path.posix.relative(SOURCE_SKILLS, rel)}`
      expected.set(target, fs.readFileSync(abs(rel)))
    }
  }

  return expected
}

// Cursor always-applies workspace files named AGENTS.md. Compiled third-party
// guides must live as REFERENCE.md so they stay on-demand only.
function listForbiddenAgentsMd() {
  const problems = []
  for (const root of [SOURCE_SKILLS, TARGET_SKILLS]) {
    for (const skill of listDirs(root)) {
      for (const rel of listFiles(`${root}/${skill}`)) {
        if (path.posix.basename(rel) === 'AGENTS.md') {
          problems.push(
            `forbidden ${rel} (rename to REFERENCE.md; Cursor always-applies AGENTS.md)`,
          )
        }
      }
    }
  }
  return problems
}

// Same skill, same behaviour in both tools: portable frontmatter only, and no
// tool names that one agent does not have.
function listParityProblems() {
  const problems = []
  for (const skill of listDirs(SOURCE_SKILLS)) {
    const rel = `${SOURCE_SKILLS}/${skill}/SKILL.md`
    if (!fs.existsSync(abs(rel))) {
      problems.push(`missing   ${rel}`)
      continue
    }
    const text = fs.readFileSync(abs(rel), 'utf8')
    const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(text)?.[1] ?? ''
    for (const line of frontmatter.split(/\r?\n/)) {
      const key = /^([\w-]+):/.exec(line)?.[1]
      if (key && !PORTABLE_SKILL_KEYS.has(key)) {
        problems.push(`parity    ${rel}: tool-specific frontmatter "${key}"`)
      }
    }
    for (const file of listFiles(`${SOURCE_SKILLS}/${skill}`)) {
      if (!file.endsWith('.md')) continue
      const tool = TOOL_ONLY_NAMES.exec(fs.readFileSync(abs(file), 'utf8'))?.[1]
      if (tool) problems.push(`parity    ${file}: names tool "${tool}"`)
    }
  }
  return problems
}

// Files in .cursor/ that this script owns: rules carrying the marker, and every
// skill folder.
function listManaged() {
  const rules = listFiles(TARGET_RULES).filter(
    (rel) =>
      rel.endsWith('.mdc') &&
      fs.readFileSync(abs(rel), 'utf8').includes(MARKER),
  )
  const skills = listDirs(TARGET_SKILLS).flatMap((skill) =>
    listFiles(`${TARGET_SKILLS}/${skill}`),
  )
  return [...rules, ...skills]
}

/** @param {Expected} expected */
function diff(expected) {
  const problems = [...listForbiddenAgentsMd(), ...listParityProblems()]
  for (const [rel, content] of expected) {
    if (!fs.existsSync(abs(rel))) problems.push(`missing   ${rel}`)
    else if (!fs.readFileSync(abs(rel)).equals(content))
      problems.push(`changed   ${rel}`)
  }
  for (const rel of listManaged()) {
    if (!expected.has(rel)) problems.push(`extra     ${rel}`)
  }
  return problems
}

/** @param {string} dirRel */
function removeEmptyDirs(dirRel) {
  const dir = abs(dirRel)
  if (!fs.existsSync(dir)) return
  for (const name of fs.readdirSync(dir)) {
    const child = path.join(dirRel, name)
    if (fs.statSync(abs(child)).isDirectory()) {
      removeEmptyDirs(child)
      if (fs.readdirSync(abs(child)).length === 0) fs.rmdirSync(abs(child))
    }
  }
}

/** @param {Expected} expected */
function write(expected) {
  for (const rel of listManaged()) {
    if (!expected.has(rel)) fs.rmSync(abs(rel))
  }
  removeEmptyDirs(TARGET_SKILLS)
  for (const [rel, content] of expected) {
    const target = abs(rel)
    if (fs.existsSync(target) && fs.readFileSync(target).equals(content))
      continue
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
    const source = rel.startsWith(TARGET_SKILLS)
      ? abs(SOURCE_SKILLS + rel.slice(TARGET_SKILLS.length))
      : null
    if (source) fs.chmodSync(target, fs.statSync(source).mode)
  }
}

function main() {
  const mode = process.argv[2]
  if (mode !== '--write' && mode !== '--check') {
    console.error('Usage: node scripts/sync-agents.mjs --write | --check')
    process.exit(2)
  }
  const expected = buildExpected()
  if (mode === '--write') write(expected)
  const problems = diff(expected)
  if (problems.length > 0) {
    console.error(`.cursor/ is out of sync with .claude/ (${problems.length}):`)
    for (const line of problems) console.error(`  ${line}`)
    if (problems.some((line) => line.startsWith('parity'))) {
      console.error(
        'Parity items: edit the skill in .claude/skills (sync cannot fix them).',
      )
    }
    console.error(
      mode === '--check'
        ? 'Run: yarn agents:sync'
        : 'Fix the items above by hand.',
    )
    process.exit(1)
  }
  console.log(
    `.cursor/ is in sync with .claude/ (${expected.size} generated files).`,
  )
}

main()
